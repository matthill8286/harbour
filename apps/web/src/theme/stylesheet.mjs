import { BrandInputsSchema, deriveTokens, toStylesheet } from '@atomic-ui/design-tokens';

/**
 * Values Harbour sets that brand inputs do not cover. The canvas is Figma's
 * bg/canvas, the colour behind the rounded app frame.
 */
const EXTRAS = `:root {
  --impakt-shell-canvas: #DCE3E2;
}
`;

/** Harbour's token stylesheet, from its brand inputs. Fonts load from theme/fonts.css, so no @font-face is written. */
export function harbourStylesheet(inputs) {
  const brand = BrandInputsSchema.parse(inputs);
  const header = '/* Generated by scripts/build-theme.mjs from src/theme/harbour-brand.json. Do not edit; run the script. */\n';
  return `${header}${toStylesheet(deriveTokens(brand), { selector: ':root', fonts: [] })}\n${EXTRAS}`;
}
